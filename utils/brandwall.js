/* 圆角矩形（只加路径、不描边，供批量合并用）。
 * 不用 ctx.roundRect —— AIUI Canvas 契约未承诺该 API。 */
function addRoundRect(ctx, x, y, w, h, r) {
  ctx.moveTo(x + r, y);
  ctx.lineTo(x + w - r, y);
  ctx.quadraticCurveTo(x + w, y, x + w, y + r);
  ctx.lineTo(x + w, y + h - r);
  ctx.quadraticCurveTo(x + w, y + h, x + w - r, y + h);
  ctx.lineTo(x + r, y + h);
  ctx.quadraticCurveTo(x, y + h, x, y + h - r);
  ctx.lineTo(x, y + r);
  ctx.quadraticCurveTo(x, y, x + r, y);
  ctx.closePath();
}

/* 一面品牌墙。
 *
 * 参数：
 *   ctx      画布上下文（调用方已完成 save / clip / translate）
 *   x, y     墙左上角（**世界坐标**，随相机滑动）
 *   o.cols / o.rows   列数 / 行数
 *   o.cellW / o.cellH 格宽 / 格高
 *   o.logoD  logo 直径（默认 22，数据框就是 22，k=1）
 *   o.boxW / o.r      格子描边框边长 / 圆角
 *   o.shift  品牌循环偏移（右墙传 2）
 *   o.fill / o.stroke 颜色串（含 alpha 的 rgba）
 *   o.visL / o.visR   **本地坐标**下的可见区间（= 屏幕裁剪窗 ± 相机偏移），
 *                     区间外的整列直接跳过 —— 墙 89% 的时间处于被裁状态，
 *                     这条剔除是性能关键。
 */
export function drawBrandWall(ctx, x, y, o) {
  const cols = o.cols, rows = o.rows;
  const cw = o.cellW, ch = o.cellH;
  const k = (o.logoD || 22) / 22;
  const visL = o.visL === undefined ? -1e9 : o.visL;
  const visR = o.visR === undefined ? 1e9 : o.visR;
  const shift = o.shift || 0;
  const boxW = o.boxW, half = (cw - boxW) / 2;
  let c, r, i, j, gx, gy, poly, p, cx0, cy0;

  /* 1) 格子描边框：一次 stroke */
  if (o.stroke) {
    ctx.beginPath();
    for (c = 0; c < cols; c++) {
      gx = x + c * cw;
      if (gx + cw <= visL || gx >= visR) continue;
      for (r = 0; r < rows; r++) {
        gy = y + r * ch;
        addRoundRect(ctx, gx + half, gy + (ch - boxW) / 2, boxW, boxW, o.r);
      }
    }
    ctx.strokeStyle = o.stroke;
    ctx.lineWidth = 1;
    ctx.stroke();
  }

  /* 2) logo：一次 fill（所有子路径合并，nonzero，孔洞已在数据里反向） */
  ctx.beginPath();
  for (c = 0; c < cols; c++) {
    gx = x + c * cw;
    if (gx + cw <= visL || gx >= visR) continue;
    for (r = 0; r < rows; r++) {
      poly = BRAND_POLY[BRANDS[(r + c + shift) % 4]];
      if (!poly) continue;
      cx0 = gx + cw / 2;
      cy0 = y + r * ch + ch / 2;
      for (i = 0; i < poly.length; i++) {
        p = poly[i];
        ctx.moveTo(cx0 + p[0] * k, cy0 + p[1] * k);
        for (j = 2; j < p.length; j += 2) {
          ctx.lineTo(cx0 + p[j] * k, cy0 + p[j + 1] * k);
        }
        ctx.closePath();
      }
    }
  }
  ctx.fillStyle = o.fill;
  ctx.fill();
}
